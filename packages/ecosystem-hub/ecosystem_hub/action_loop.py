"""Shared action loop for autonomous cyber operations.

Executes autonomous action proposals generated by an analyst model, gated
by the PolicyEngine and dispatched through the Hub capability network.

Invariants enforced:
1. Denied or approval-pending proposals are never dispatched to the hub.
2. Mid-loop Freeze immediately halts remaining steps.
3. max_steps bounds model iteration.
4. ActionTimeline preserves full audit records even on provider error.
"""
from __future__ import annotations

import inspect
import logging
import time
from dataclasses import asdict, dataclass, field
from typing import Any

from ecosystem_client.contracts import Proposal, UnusableModelOutput, parse_proposals
from ecosystem_client.ulid import generate_ulid
from ecosystem_policy.models import ActionRequest

from .command_common import is_internal_subject, policy_target

logger = logging.getLogger(__name__)


@dataclass
class ActionStep:
    """A single step evaluated and/or executed in an action loop."""

    step_number: int
    proposal: Proposal
    decision: str  # "allow" | "allow_and_notify" | "require_approval" | "deny" | "frozen"
    decision_reason: str
    command_id: str | None = None
    status: str = "pending"  # "completed" | "accepted" | "pending_approval" | "denied" | "failed" | "provider_unavailable" | "skipped_frozen"
    result: Any = None
    error: str | None = None
    approval_id: str | None = None
    outcome_unknown: bool = False
    idempotency_key: str | None = None
    timestamp: float = field(default_factory=time.time)

    def to_dict(self) -> dict[str, Any]:
        prop_data = self.proposal.to_dict() if hasattr(self.proposal, "to_dict") else asdict(self.proposal)
        return {
            "step_number": self.step_number,
            "proposal": prop_data,
            "decision": self.decision,
            "decision_reason": self.decision_reason,
            "command_id": self.command_id,
            "status": self.status,
            "result": self.result,
            "error": self.error,
            "approval_id": self.approval_id,
            "outcome_unknown": self.outcome_unknown,
            "idempotency_key": self.idempotency_key,
            "timestamp": self.timestamp,
        }


@dataclass
class ActionTimeline:
    """Consolidated record of an action loop session for UI rendering and audits."""

    session_id: str
    request: str
    steps: list[ActionStep] = field(default_factory=list)
    completed: bool = False
    stopped_reason: str = ""  # "completed" | "frozen" | "max_steps_exceeded" | "no_more_proposals" | "unusable_model_output" | "reconciliation_needed" | "error"
    error: str | None = None
    created_at: float = field(default_factory=time.time)
    updated_at: float = field(default_factory=time.time)

    def to_dict(self) -> dict[str, Any]:
        return {
            "session_id": self.session_id,
            "request": self.request,
            "steps": [s.to_dict() for s in self.steps],
            "completed": self.completed,
            "stopped_reason": self.stopped_reason,
            "error": self.error,
            "created_at": self.created_at,
            "updated_at": self.updated_at,
        }


def _normalize_command_target(raw: Any) -> dict[str, Any]:
    """Convert proposal target into canonical command schema target {scope, identifier, ...}."""
    if isinstance(raw, dict):
        scope = raw.get("scope")
        identifier = raw.get("identifier") or raw.get("target") or raw.get("host")
        if not scope:
            scope = "external" if (identifier and not is_internal_subject(identifier)) else "local"
        res: dict[str, Any] = {"scope": scope}
        for k in ("device_id", "service"):
            if raw.get(k) is not None:
                res[k] = raw[k]
        if identifier is not None:
            res["identifier"] = str(identifier)
        return res
    if isinstance(raw, str):
        scope = "external" if not is_internal_subject(raw) else "local"
        return {"scope": scope, "identifier": raw}
    return {"scope": "local"}


async def _call_analyst(analyst: Any, request: str, context: dict[str, Any]) -> list[Proposal]:
    """Invoke the analyst and return validated Proposals."""
    if hasattr(analyst, "propose"):
        out = analyst.propose(request, context)
    elif callable(analyst):
        out = analyst(request, context)
    else:
        raise ValueError(f"analyst {analyst!r} is neither callable nor exposes propose()")

    if inspect.isawaitable(out):
        out = await out

    if isinstance(out, list) and all(isinstance(x, Proposal) for x in out):
        return out

    raw_text = getattr(out, "text", out)
    if not isinstance(raw_text, str):
        raise UnusableModelOutput(f"expected text output from analyst, got {type(raw_text).__name__}")

    return parse_proposals(raw_text)


async def _decide(policy: Any, req: ActionRequest) -> Any:
    out = policy.decide(req)
    if inspect.isawaitable(out):
        return await out
    return out


async def _is_frozen(policy: Any) -> bool:
    if hasattr(policy, "is_frozen"):
        f = policy.is_frozen
        val = f() if callable(f) else f
        if inspect.isawaitable(val):
            return await val
        return bool(val)
    if hasattr(policy, "frozen"):
        f = policy.frozen
        val = f() if callable(f) else f
        if inspect.isawaitable(val):
            return await val
        return bool(val)
    return False


async def run_action_loop(
    request: str,
    context: dict[str, Any] | None = None,
    *,
    analyst: Any,
    policy: Any,
    hub: Any,
    max_steps: int = 5,
    max_rounds: int | None = None,
    actor: str = "action_loop",
) -> ActionTimeline:
    """Run the shared action loop with fail-closed guardrails.

    Asks the analyst for proposals, validates against schema, decides each via
    the policy engine, dispatches allowed proposals via hub.invoke, collects
    results, and optionally feeds results back for a bounded follow-up round.
    """
    timeline = ActionTimeline(
        session_id=generate_ulid(),
        request=request,
    )

    if await _is_frozen(policy):
        timeline.completed = True
        timeline.stopped_reason = "frozen"
        timeline.updated_at = time.time()
        return timeline

    current_context = dict(context or {})
    steps_executed = 0
    round_num = 0
    effective_max_rounds = max_rounds if max_rounds is not None else max_steps

    while round_num < effective_max_rounds and steps_executed < max_steps:
        round_num += 1

        # Check freeze before asking analyst
        if await _is_frozen(policy):
            timeline.completed = True
            timeline.stopped_reason = "frozen"
            break

        try:
            proposals = await _call_analyst(analyst, request, current_context)
        except UnusableModelOutput as exc:
            timeline.stopped_reason = "unusable_model_output"
            timeline.error = str(exc)
            timeline.completed = True
            break
        except Exception as exc:
            timeline.stopped_reason = "error"
            timeline.error = f"analyst failed: {exc}"
            timeline.completed = True
            break

        if not proposals:
            timeline.stopped_reason = "no_more_proposals"
            timeline.completed = True
            break

        dispatched_in_round = 0

        for proposal in proposals:
            if steps_executed >= max_steps:
                timeline.stopped_reason = "max_steps_exceeded"
                break

            steps_executed += 1
            step_num = len(timeline.steps) + 1

            # Invariant 2: Mid-loop Freeze immediately halts remaining steps
            if await _is_frozen(policy):
                timeline.steps.append(
                    ActionStep(
                        step_number=step_num,
                        proposal=proposal,
                        decision="frozen",
                        decision_reason="System is in emergency freeze",
                        status="skipped_frozen",
                    )
                )
                timeline.stopped_reason = "frozen"
                timeline.completed = True
                break

            cmd_target = _normalize_command_target(proposal.target)
            req_target = policy_target(cmd_target, proposal.action_class, proposal.parameters)
            req = ActionRequest(
                actor=actor,
                action=proposal.action,
                action_class=proposal.action_class,
                target=req_target,
                rationale=proposal.rationale,
                context=current_context,
            )

            decision = await _decide(policy, req)
            decision_result = getattr(decision, "result", "deny")
            decision_reason = getattr(decision, "reason", "")

            # Invariant 1: Denied or approval-pending proposals are never dispatched
            if decision_result in ("deny", "require_approval"):
                appr_id = None
                if decision_result == "require_approval":
                    if hasattr(hub, "request_approval") and callable(hub.request_approval):
                        try:
                            resp = hub.request_approval(
                                capability=proposal.action,
                                action_class=proposal.action_class,
                                target=cmd_target,
                                rationale=proposal.rationale,
                                decision=decision,
                            )
                            if inspect.isawaitable(resp):
                                resp = await resp
                            if isinstance(resp, dict):
                                appr_id = resp.get("approval_id")
                        except Exception as exc:
                            logger.warning("hub.request_approval failed: %s", exc)
                    elif hasattr(policy, "create_approval_request") and callable(policy.create_approval_request):
                        try:
                            resp = policy.create_approval_request(req, decision)
                            if inspect.isawaitable(resp):
                                resp = await resp
                            if isinstance(resp, dict):
                                appr_id = resp.get("approval_id")
                        except Exception as exc:
                            logger.warning("policy.create_approval_request failed: %s", exc)
                    elif getattr(decision, "approval_id", None):
                        appr_id = getattr(decision, "approval_id")
                    elif getattr(decision, "grant_id", None):
                        appr_id = getattr(decision, "grant_id")

                    if not appr_id:
                        try:
                            from ecosystem_policy.approval_queue import LocalApprovalQueue

                            q = LocalApprovalQueue()
                            rec = q.request_approval(
                                requester_service=actor,
                                actor=actor,
                                action=proposal.action,
                                action_class=proposal.action_class,
                                target=cmd_target,
                                summary=proposal.rationale or f"{actor}: {proposal.action}",
                                policy_version=getattr(decision, "policy_version", 3),
                                mode=getattr(decision, "mode", "normal"),
                                ttl_seconds=getattr(decision, "ttl_seconds", 3600),
                            )
                            appr_id = rec.get("approval_id")
                        except Exception as exc:
                            logger.warning("Failed creating approval queue record: %s", exc)

                timeline.steps.append(
                    ActionStep(
                        step_number=step_num,
                        proposal=proposal,
                        decision=decision_result,
                        decision_reason=decision_reason,
                        status="denied" if decision_result == "deny" else "pending_approval",
                        approval_id=appr_id,
                    )
                )
                continue

            # Policy allowed: double check freeze before dispatch
            if await _is_frozen(policy):
                timeline.steps.append(
                    ActionStep(
                        step_number=step_num,
                        proposal=proposal,
                        decision="frozen",
                        decision_reason="System froze before dispatch",
                        status="skipped_frozen",
                    )
                )
                timeline.stopped_reason = "frozen"
                timeline.completed = True
                break

            # Dispatch allowed proposal through hub
            step_key = generate_ulid()
            cmd_id = None
            status = "completed"
            result = None
            error = None
            appr_id = None
            outcome_unknown = False

            try:
                invoke_kwargs: dict[str, Any] = {
                    "capability": proposal.action,
                    "target": cmd_target,
                    "parameters": proposal.parameters,
                    "rationale": proposal.rationale,
                }
                try:
                    sig = inspect.signature(hub.invoke)
                    if "idempotency_key" in sig.parameters or any(
                        p.kind == inspect.Parameter.VAR_KEYWORD for p in sig.parameters.values()
                    ):
                        invoke_kwargs["idempotency_key"] = step_key
                except (ValueError, TypeError):
                    invoke_kwargs["idempotency_key"] = step_key

                invoke_out = hub.invoke(**invoke_kwargs)
                if inspect.isawaitable(invoke_out):
                    invoke_out = await invoke_out

                if isinstance(invoke_out, dict):
                    status = invoke_out.get("status", "completed")
                    cmd_id = invoke_out.get("command_id")
                    result = invoke_out.get("result")
                    error = invoke_out.get("error")
                    appr_id = invoke_out.get("approval_id")
                    outcome_unknown = bool(invoke_out.get("outcome_unknown", False))
                else:
                    result = invoke_out
                dispatched_in_round += 1
            except Exception as exc:
                # Invariant 4: Preserve full audit records even on provider error
                status = "failed"
                error = str(exc)

            timeline.steps.append(
                ActionStep(
                    step_number=step_num,
                    proposal=proposal,
                    decision=decision_result,
                    decision_reason=decision_reason,
                    command_id=cmd_id,
                    status=status,
                    result=result,
                    error=error,
                    approval_id=appr_id,
                    outcome_unknown=outcome_unknown,
                    idempotency_key=step_key,
                )
            )

            if outcome_unknown:
                timeline.stopped_reason = "reconciliation_needed"
                timeline.error = f"Step {step_num} ({proposal.action}) resulted in an unknown outcome; stopping for reconciliation."
                timeline.completed = True
                break

        if timeline.stopped_reason in ("frozen", "max_steps_exceeded", "unusable_model_output", "reconciliation_needed", "error"):
            break

        # Follow-up round setup: feed step results into context
        prior_steps = current_context.setdefault("prior_steps", [])
        for step in timeline.steps[-len(proposals):]:
            prior_steps.append({
                "action": step.proposal.action,
                "status": step.status,
                "result": step.result,
                "error": step.error,
                "outcome_unknown": step.outcome_unknown,
            })

        # If no allowed actions were executed, no need for another follow-up round
        if dispatched_in_round == 0:
            timeline.stopped_reason = "completed"
            timeline.completed = True
            break

    if not timeline.stopped_reason:
        timeline.stopped_reason = "completed" if steps_executed < max_steps else "max_steps_exceeded"
    timeline.completed = True
    timeline.updated_at = time.time()
    return timeline
